const LANG = (() => {
  for (const l of navigator.languages || [navigator.language || '']) {
    const code = String(l).slice(0, 2).toLowerCase();
    if (code === 'pl' || code === 'en') return code;
  }
  return 'en';
})();
const LOCALE = LANG === 'pl' ? 'pl-PL' : 'en-GB';

function t(pl, vars) {
  const s = LANG === 'pl' ? pl : (I18N_EN[pl] ?? pl);
  return vars ? s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? vars[k] : m)) : s;
}

function tn(n, forms, vars) {
  const list = t(forms).split('|');
  const order = LANG === 'pl' ? ['one', 'few', 'many'] : ['one', 'other'];
  const i = order.indexOf(new Intl.PluralRules(LOCALE).select(n));
  const form = list[i < 0 ? list.length - 1 : Math.min(i, list.length - 1)];
  return form.replace(/\{(\w+)\}/g, (m, k) => (k === 'n' ? n : vars && k in vars ? vars[k] : m));
}

// Static markup: data-i18n translates the element's content (its normalized inner HTML is the key);
// data-i18n-attr="placeholder title" translates those attributes.
function applyI18n(root = document) {
  document.documentElement.lang = LANG;
  for (const el of root.querySelectorAll('[data-i18n]')) {
    el.innerHTML = t(el.innerHTML.trim().replace(/\s+/g, ' '));
  }
  for (const el of root.querySelectorAll('[data-i18n-attr]')) {
    for (const a of el.dataset.i18nAttr.split(' ')) el.setAttribute(a, t(el.getAttribute(a)));
  }
}
